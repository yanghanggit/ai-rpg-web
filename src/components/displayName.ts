/**
 * 服务器上的正式名字 → 客户端显示用的名字。
 *
 * 服务器给实体取名时带上类型前缀，用 `.` 分段：`角色.无名`、`场景.门厅`、
 * `装备.缠麻短刃`、`世界.副本生成系统`、`怪物.纸人`、`副本.坍塌庙祠`
 * ——也可能出现更多层（`a.b.c`）。前缀对玩家没有意义，所以只保留**最后一段**。
 *
 *   displayName("角色.无名")      → "无名"
 *   displayName("场景.门厅")      → "门厅"
 *   displayName("装备.缠麻短刃")  → "缠麻短刃"
 *   displayName("a.b.c")          → "c"
 *   displayName("Game1")          → "Game1"   // 没有分隔符，原样返回
 *
 * ## 只用于显示
 *
 * 取身份的地方——比较、查询、URL、API 参数、React key——一律用**原始名字**。
 * 不同前缀下会出现同名实体（`角色.无名` / `怪物.无名`），拿显示名当身份会撞。
 *
 * ## 为什么单独抽一个函数
 *
 * 「名字怎么显示」是客户端的一条业务规则，将来要改（保留前缀、加简称表、按实体类型
 * 区别对待……）只改这里一处，不要在组件里各写一份。
 */
export function displayName(name: string): string {
  // 先滤掉空段：`角色..无名` / `.无名` / `角色.` 这类脏名字也退化成"取最后一个非空段"。
  // 全部为空（""、".."）时 segments 为空数组，回退到原值，不会返回凭空造出的空串。
  const segments = name.split(".").filter((segment) => segment !== "");

  return segments[segments.length - 1] ?? name;
}
